import type { ImageInput } from '../interfaces/aiEngine.interface.js';

export interface DecodedImageMeta {
  buffer: Buffer;
  format: 'jpeg' | 'png' | 'webp' | 'unknown';
}

/**
 * Decodes input image string or buffer into clean binary Buffer.
 * Supports Base64 data URIs, raw Base64 strings, or direct binary Buffers.
 */
export function normalizeImageToBuffer(input: ImageInput): DecodedImageMeta {
  let buffer: Buffer;

  if (Buffer.isBuffer(input)) {
    buffer = input;
  } else if (typeof input === 'string') {
    // Clean base64 header if present
    const base64Clean = input.replace(/^data:image\/\w+;base64,/, '');
    buffer = Buffer.from(base64Clean, 'base64');
  } else {
    throw new Error('[ImageUtils] Invalid image input type. Expected Buffer or Base64 string.');
  }

  if (buffer.length === 0) {
    throw new Error('[ImageUtils] Empty image buffer received.');
  }

  // Detect image format from magic header bytes
  const format = detectImageFormat(buffer);

  return { buffer, format };
}

/**
 * Detect image format from magic signature bytes.
 */
export function detectImageFormat(buffer: Buffer): 'jpeg' | 'png' | 'webp' | 'unknown' {
  if (buffer.length >= 3 && buffer[0] === 0xff && buffer[1] === 0xd8 && buffer[2] === 0xff) {
    return 'jpeg';
  }
  if (buffer.length >= 8 && buffer[0] === 0x89 && buffer[1] === 0x50 && buffer[2] === 0x4e && buffer[3] === 0x47) {
    return 'png';
  }
  if (buffer.length >= 12 && buffer.subarray(8, 12).toString('ascii') === 'WEBP') {
    return 'webp';
  }
  return 'unknown';
}

